/// App UI strings in Telugu (te) and Hindi (hi), keyed by the English text.
///
/// Simple everyday words; brand names and common tech words (AI, UPI, OTP,
/// app, link) stay in English the way people say them. A missing key shows
/// English. Story text itself is translated by the AI Worker, not here.
library;

String translateUi(String english, String lang) {
  if (lang == 'te') return _te[english] ?? english;
  if (lang == 'hi') return _hi[english] ?? english;
  return english;
}

/// Every key the tables know (used by a test that checks both tables match).
Iterable<String> get uiStringKeys => {..._te.keys, ..._hi.keys};
bool hasUiString(String english, String lang) => (lang == 'te' ? _te : _hi).containsKey(english);

